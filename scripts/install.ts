// Install dotagents into each selected agent: instructions, skills, scripts, settings, and MCP servers.
// Usage: node scripts/install.ts [--runner] [cursor] [zed] [claude] [copilot]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { InstallError } from "./lib/json.ts";
import { loadServers } from "./mcp/declarations.ts";
import { sync } from "./mcp/sync.ts";
import { applySettings } from "./settings.ts";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET_NAMES = ["cursor", "zed", "claude", "copilot"] as const;
type Target = (typeof TARGET_NAMES)[number];
const HOME_NAMES = [
  "CURSOR_HOME",
  "ZED_HOME",
  "CLAUDE_HOME",
  "COPILOT_HOME",
  "AGENTS_HOME",
] as const;
type Homes = Record<(typeof HOME_NAMES)[number] | "HOME", string>;

// Marks AGENTS.md as generated so hand-written files are never replaced; matched by prefix
const AGENTS_MARKER_PREFIX = "<!-- Generated by install.sh";
const AGENTS_MARKER = `${AGENTS_MARKER_PREFIX} from plugins/*/rules/. Edit those files, then rerun ./install.sh. -->`;
const CURSOR_MARKER = "# Generated by dotagents";

interface Link {
  source: string;
  target: string;
}

// Agent homes from the environment, or all under RUNNER_TEMP for a CI runner
function resolveHomes(env: NodeJS.ProcessEnv, runner: boolean): Homes {
  const home = env.HOME;
  if (!home) {
    throw new InstallError("HOME is not set");
  }
  if (runner) {
    if (!env.RUNNER_TEMP || !env.GITHUB_ENV) {
      throw new InstallError(
        "--runner needs RUNNER_TEMP and GITHUB_ENV, as set by GitHub or Gitea Actions",
      );
    }
    const base = path.join(env.RUNNER_TEMP, "dotagents");
    const homes = Object.fromEntries(
      HOME_NAMES.map((name) => [
        name,
        path.join(base, name.slice(0, -"_HOME".length).toLowerCase()),
      ]),
    );
    return { HOME: home, ...homes } as Homes;
  }

  // Each home can be overridden, mainly for tests and runners
  return {
    HOME: home,
    CURSOR_HOME: env.CURSOR_HOME || path.join(home, ".cursor"),
    ZED_HOME: env.ZED_HOME || path.join(home, ".config", "zed"),
    CLAUDE_HOME: env.CLAUDE_HOME || path.join(home, ".claude"),
    COPILOT_HOME: env.COPILOT_HOME || path.join(home, ".copilot"),
    AGENTS_HOME: env.AGENTS_HOME || path.join(home, ".agents"),
  };
}

// Check every target name before doing anything; no names means every agent
function parseTargets(args: string[], runner: boolean): Target[] {
  for (const arg of args) {
    if (!(TARGET_NAMES as readonly string[]).includes(arg)) {
      throw new InstallError(`unknown target '${arg}' (expected cursor, zed, claude, or copilot)`);
    }
  }
  if (args.length === 0) {
    return runner ? ["copilot"] : [...TARGET_NAMES];
  }
  return args as Target[];
}

// Sorted entries of a folder, skipping hidden ones as shell globs do, or none when it doesn't exist
function list(dir: string): string[] {
  return fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((name) => !name.startsWith("."))
        .sort()
    : [];
}

const isDirectory = (file: string) =>
  fs.statSync(file, { throwIfNoEntry: false })?.isDirectory() ?? false;

// The committed defaults plugin loads first, then every other plugin in name order
function findPlugins(): string[] {
  const pluginsDir = path.join(REPO_ROOT, "plugins");
  const defaults = path.join(pluginsDir, "dotagents-defaults");
  const others = list(pluginsDir)
    .map((name) => path.join(pluginsDir, name))
    .filter((dir) => dir !== defaults && isDirectory(dir));
  return [defaults, ...others];
}

// Collect one kind of plugin content by name, failing on a name two plugins share
function collect(
  plugins: string[],
  { kind, accept }: { kind: string; accept: (file: string) => boolean },
) {
  const found = new Map<string, { source: string; plugin: string }>();
  for (const plugin of plugins) {
    const dir = path.join(plugin, `${kind}s`);
    for (const name of list(dir).filter((entry) => accept(path.join(dir, entry)))) {
      const owner = found.get(name);
      if (owner) {
        throw new InstallError(
          `${kind} '${name}' is in both plugins/${owner.plugin} and plugins/${path.basename(plugin)} — rename one of them`,
        );
      }
      found.set(name, { source: path.join(dir, name), plugin: path.basename(plugin) });
    }
  }
  return found;
}

// True when a path is a regular file this process may execute
function isExecutable(file: string): boolean {
  try {
    fs.accessSync(file, fs.constants.X_OK);
    return fs.statSync(file).isFile();
  } catch {
    return false;
  }
}

// Every plugin's rules in load order, each plugin's in filename order; defaults must have some
function findRules(plugins: string[]): string[] {
  const rulesOf = (plugin: string) =>
    list(path.join(plugin, "rules"))
      .filter((name) => name.endsWith(".md"))
      .map((name) => path.join(plugin, "rules", name));
  const [defaults = "", ...others] = plugins;
  const rules = rulesOf(defaults);
  if (rules.length === 0) {
    throw new InstallError(`no rules found in ${path.join(defaults, "rules")}`);
  }
  return [...rules, ...others.flatMap(rulesOf)];
}

const hasLine = (file: string, test: (line: string) => boolean) =>
  fs.readFileSync(file, "utf8").split("\n").some(test);

// Links may replace other links, but never a file or folder someone made by hand
function checkLink({ target }: Link): void {
  const stat = fs.lstatSync(target, { throwIfNoEntry: false });
  if (stat && !stat.isSymbolicLink()) {
    throw new InstallError(`${target} exists and is not a symlink — move or remove it first`);
  }
}

// Point target at source, replacing any earlier link so moving the repository stays recoverable
function link({ source, target }: Link): void {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.rmSync(target, { force: true });
  fs.symlinkSync(source, target);
  console.log(`linked ${target} -> ${source}`);
}

// Write a file by swapping in a sibling, so readers never see it half-written
function writeFile(file: string, text: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temporary = path.join(path.dirname(file), `.${path.basename(file)}.tmp`);
  fs.writeFileSync(temporary, text);
  fs.renameSync(temporary, file);
}

function main(argv: string[]): void {
  // Parse options, targets, and homes
  const runner = argv[0] === "--runner";
  const targets = parseTargets(runner ? argv.slice(1) : argv, runner);
  const homes = resolveHomes(process.env, runner);
  const has = (target: Target) => targets.includes(target);
  const agents = path.join(REPO_ROOT, "AGENTS.md");

  // Find plugin content, failing on names two plugins share
  const plugins = findPlugins();
  const skills = collect(plugins, { kind: "skill", accept: isDirectory });
  const scripts = collect(plugins, { kind: "script", accept: isExecutable });
  const rules = findRules(plugins);

  // Settings overlays each selected agent gets, checked before anything changes
  const settings: { target: Target; overlay: string; file: string }[] = [];
  if (has("claude")) {
    settings.push({
      target: "claude",
      overlay: path.join(REPO_ROOT, "settings", "claude.json"),
      file: path.join(homes.CLAUDE_HOME, "settings.json"),
    });
  }
  if (has("copilot")) {
    settings.push({
      target: "copilot",
      overlay: path.join(REPO_ROOT, "settings", "copilot.json"),
      file: path.join(homes.COPILOT_HOME, "settings.json"),
    });
  }
  settings.forEach(({ overlay, file }) => applySettings(overlay, file, { check: true }));

  // MCP servers sync when any are declared, or to prune ones installed earlier
  // On-demand servers stay out of agent configs; agents reach them through mcp-call
  const servers = loadServers(plugins, { home: homes.HOME, searchPath: process.env.PATH }).filter(
    (server) => !server.onDemand,
  );
  const runMcp =
    servers.length > 0 || fs.existsSync(path.join(homes.AGENTS_HOME, "state", "mcp.json"));
  if (runMcp) {
    sync({ servers, targets, env: homes, check: true });
  }

  // Instruction links per agent; Cursor gets a generated adapter instead
  const instructionLinks: Partial<Record<Target, Link>> = {
    ...(has("zed") && { zed: { source: agents, target: path.join(homes.ZED_HOME, "AGENTS.md") } }),
    ...(has("claude") && {
      claude: { source: agents, target: path.join(homes.CLAUDE_HOME, "CLAUDE.md") },
    }),
    ...(has("copilot") && {
      copilot: { source: agents, target: path.join(homes.COPILOT_HOME, "copilot-instructions.md") },
    }),
  };
  const skillDirs = [
    ...(["cursor", "zed", "copilot"].some((target) => has(target as Target))
      ? [path.join(homes.AGENTS_HOME, "skills")]
      : []),
    ...(has("claude") ? [path.join(homes.CLAUDE_HOME, "skills")] : []),
  ];
  const skillLinks = skillDirs.flatMap((dir) =>
    [...skills].map(([name, { source }]) => ({ source, target: path.join(dir, name) })),
  );
  const scriptLinks = [...scripts].map(([name, { source }]) => ({
    source,
    target: path.join(homes.AGENTS_HOME, "bin", name),
  }));

  // Refuse to replace anything this installer didn't make, before changing anything
  if (fs.existsSync(agents) && !hasLine(agents, (line) => line.startsWith(AGENTS_MARKER_PREFIX))) {
    throw new InstallError(
      `${agents} was not generated by install.sh — move its rules into a plugin's rules/ folder, then remove it`,
    );
  }
  const cursorAdapter = path.join(homes.CURSOR_HOME, "rules", "dotagents.mdc");
  if (
    has("cursor") &&
    fs.existsSync(cursorAdapter) &&
    !hasLine(cursorAdapter, (line) => line === CURSOR_MARKER)
  ) {
    throw new InstallError(`${cursorAdapter} exists and is not managed by dotagents`);
  }
  [...Object.values(instructionLinks), ...skillLinks, ...scriptLinks].forEach(checkLink);

  // Generate AGENTS.md from every rule, joined by blank lines
  writeFile(
    agents,
    `${AGENTS_MARKER}\n${rules.map((rule) => `\n${fs.readFileSync(rule, "utf8")}`).join("")}`,
  );
  console.log(`generated ${agents} from ${rules.length} rule files`);

  // Install each selected agent in the order given
  for (const target of targets) {
    if (target === "cursor") {
      const header =
        "---\ndescription: Personal instructions shared across coding agents\nalwaysApply: true\n---\n\n";
      writeFile(cursorAdapter, `${header}${CURSOR_MARKER}\n\n${fs.readFileSync(agents, "utf8")}`);
      console.log(`generated ${cursorAdapter} from ${agents}`);
    }
    const instructions = instructionLinks[target];
    if (instructions) {
      link(instructions);
    }
    settings
      .filter((setting) => setting.target === target)
      .forEach(({ overlay, file }) => applySettings(overlay, file));
  }

  // Skills, scripts, then MCP servers, which also prunes servers no longer declared
  skillLinks.forEach(link);
  scriptLinks.forEach(link);
  if (runMcp) {
    sync({ servers, targets, env: homes });
  }

  // On a runner, point later steps at the homes just installed
  if (runner) {
    const lines = HOME_NAMES.map((name) => `${name}=${homes[name]}\n`).join("");
    fs.appendFileSync(process.env.GITHUB_ENV ?? "", lines);
  }
  console.log("done");
}

try {
  main(process.argv.slice(2));
} catch (error) {
  // Expected failures print one line; filesystem errors carry paths but not configuration values
  if (error instanceof InstallError || (error as NodeJS.ErrnoException).code) {
    console.error(`error: ${(error as Error).message}`);
    process.exit(1);
  }
  throw error;
}
