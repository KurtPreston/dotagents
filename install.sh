#!/usr/bin/env bash
set -euo pipefail

# Resolve repository and configurable agent homes
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CURSOR_HOME="${CURSOR_HOME:-$HOME/.cursor}"
ZED_HOME="${ZED_HOME:-$HOME/.config/zed}"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
AGENTS_HOME="${AGENTS_HOME:-$HOME/.agents}"

# Default to installing every supported integration
if [[ "$#" -eq 0 ]]; then
  set -- cursor zed claude
fi

# Track shared installation work across selected agents
INSTALL_SHARED_SKILLS=false
INSTALL_CLAUDE_SKILLS=false

link_file() {
  local source="$1"
  local target="$2"

  # Refuse to replace user-managed files
  mkdir -p "$(dirname "$target")"
  if [[ -e "$target" && ! -L "$target" ]]; then
    echo "error: $target exists and is not a symlink — move or remove it first" >&2
    exit 1
  fi

  # Refresh links so moving the repository remains recoverable
  ln -sfn "$source" "$target"
  echo "linked $target -> $source"
}

link_skills() {
  local target_dir="$1"
  local skill source target

  # Link each skill without replacing the destination directory
  mkdir -p "$target_dir"
  shopt -s nullglob
  for source in "$REPO_ROOT"/skills/*/; do
    skill="$(basename "$source")"
    target="$target_dir/$skill"
    link_file "${source%/}" "$target"
  done
  shopt -u nullglob
}

install_cursor() {
  local target="$CURSOR_HOME/rules/dotagents.mdc"

  # Protect existing rules not generated by this repository
  mkdir -p "$CURSOR_HOME/rules"
  if [[ -e "$target" ]] && ! grep -q '^# Generated by dotagents$' "$target"; then
    echo "error: $target exists and is not managed by dotagents" >&2
    exit 1
  fi

  # Add Cursor metadata around the canonical instructions
  {
    printf '%s\n' '---' 'description: Personal instructions shared across coding agents' 'alwaysApply: true' '---' ''
    printf '%s\n\n' '# Generated by dotagents'
    cat "$REPO_ROOT/AGENTS.md"
  } > "$target"
  echo "generated $target from $REPO_ROOT/AGENTS.md"

  INSTALL_SHARED_SKILLS=true
}

install_zed() {
  # Zed reads this global file in every agent session
  link_file "$REPO_ROOT/AGENTS.md" "$ZED_HOME/AGENTS.md"
  INSTALL_SHARED_SKILLS=true
}

install_claude() {
  # Claude Code uses CLAUDE.md for personal standing instructions
  link_file "$REPO_ROOT/AGENTS.md" "$CLAUDE_HOME/CLAUDE.md"
  INSTALL_CLAUDE_SKILLS=true
}

# Install only the explicitly selected agent integrations
for target in "$@"; do
  case "$target" in
    cursor) install_cursor ;;
    zed) install_zed ;;
    claude) install_claude ;;
    *)
      echo "error: unknown target '$target' (expected cursor, zed, or claude)" >&2
      exit 1
      ;;
  esac
done

# Cursor and Zed share the open Agent Skills location
if [[ "$INSTALL_SHARED_SKILLS" == true ]]; then
  link_skills "$AGENTS_HOME/skills"
fi
if [[ "$INSTALL_CLAUDE_SKILLS" == true ]]; then
  link_skills "$CLAUDE_HOME/skills"
fi

echo "done"
