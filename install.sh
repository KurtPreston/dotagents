#!/usr/bin/env bash
set -euo pipefail

# Resolve repository and configurable agent homes
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CURSOR_HOME="${CURSOR_HOME:-$HOME/.cursor}"
ZED_HOME="${ZED_HOME:-$HOME/.config/zed}"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
COPILOT_HOME="${COPILOT_HOME:-$HOME/.copilot}"
AGENTS_HOME="${AGENTS_HOME:-$HOME/.agents}"

# Default to installing every supported integration
if [[ "$#" -eq 0 ]]; then
  set -- cursor zed claude copilot
fi

# Validate every target before installing any integration
INSTALL_CLAUDE_SETTINGS=false
INSTALL_COPILOT_SETTINGS=false
for target in "$@"; do
  case "$target" in
    cursor|zed) ;;
    claude) INSTALL_CLAUDE_SETTINGS=true ;;
    copilot) INSTALL_COPILOT_SETTINGS=true ;;
    *)
      echo "error: unknown target '$target' (expected cursor, zed, claude, or copilot)" >&2
      exit 1
      ;;
  esac
done

# Settings merges need Python before any mutation happens
if [[ "$INSTALL_CLAUDE_SETTINGS" == true || "$INSTALL_COPILOT_SETTINGS" == true ]]; then
  if ! command -v python3 >/dev/null 2>&1; then
    echo "error: Claude and Copilot settings require Python 3; install python3 and rerun ./install.sh" >&2
    exit 1
  fi
fi

# Fail before mutations when any selected settings cannot be safely merged
if [[ "$INSTALL_CLAUDE_SETTINGS" == true ]]; then
  python3 "$REPO_ROOT/scripts/merge-settings.py" --check \
    "$REPO_ROOT/settings/claude.json" "$CLAUDE_HOME/settings.json"
fi
if [[ "$INSTALL_COPILOT_SETTINGS" == true ]]; then
  python3 "$REPO_ROOT/scripts/merge-settings.py" --check \
    "$REPO_ROOT/settings/copilot.json" "$COPILOT_HOME/settings.json"
fi

# Marks AGENTS.md as generated so hand-written files are never replaced
AGENTS_MARKER='<!-- Generated by install.sh from rules/ and rules-local/. Edit those files, then rerun ./install.sh. -->'

generate_agents() {
  local target="$REPO_ROOT/AGENTS.md"
  local temp="$REPO_ROOT/.AGENTS.md.tmp"
  local rules=() rule

  # Refuse to replace an AGENTS.md this installer did not generate
  if [[ -e "$target" ]] && ! grep -qxF "$AGENTS_MARKER" "$target"; then
    echo "error: $target was not generated by install.sh — move its rules into rules/ or rules-local/, then remove it" >&2
    exit 1
  fi

  # Shared rules come first, then this machine's rules, each in filename order
  shopt -s nullglob
  rules=("$REPO_ROOT"/rules/*.md)
  if [[ "${#rules[@]}" -eq 0 ]]; then
    echo "error: no rules found in $REPO_ROOT/rules" >&2
    exit 1
  fi
  rules+=("$REPO_ROOT"/rules-local/*.md)
  shopt -u nullglob

  # Join rules with blank lines, then swap the file in so readers never see a partial file
  {
    printf '%s\n' "$AGENTS_MARKER"
    for rule in "${rules[@]}"; do
      printf '\n'
      cat "$rule"
    done
  } > "$temp"
  mv -f "$temp" "$target"
  echo "generated $target from ${#rules[@]} rule files"
}

# Every integration reads the generated instructions
generate_agents

# Track shared installation work across selected agents
INSTALL_SHARED_SKILLS=false
INSTALL_CLAUDE_SKILLS=false

link_file() {
  local source="$1"
  local target="$2"

  # Refuse to replace user-managed files
  mkdir -p "$(dirname "$target")"
  if [[ -e "$target" && ! -L "$target" ]]; then
    echo "error: $target exists and is not a symlink — move or remove it first" >&2
    exit 1
  fi

  # Refresh links so moving the repository remains recoverable
  ln -sfn "$source" "$target"
  echo "linked $target -> $source"
}

link_skills() {
  local target_dir="$1"
  local skill source target

  # Link each skill without replacing the destination directory
  mkdir -p "$target_dir"
  shopt -s nullglob
  for source in "$REPO_ROOT"/skills/*/; do
    skill="$(basename "$source")"
    target="$target_dir/$skill"
    link_file "${source%/}" "$target"
  done
  shopt -u nullglob
}

install_cursor() {
  local target="$CURSOR_HOME/rules/dotagents.mdc"

  # Protect existing rules not generated by this repository
  mkdir -p "$CURSOR_HOME/rules"
  if [[ -e "$target" ]] && ! grep -q '^# Generated by dotagents$' "$target"; then
    echo "error: $target exists and is not managed by dotagents" >&2
    exit 1
  fi

  # Add Cursor metadata around the canonical instructions
  {
    printf '%s\n' '---' 'description: Personal instructions shared across coding agents' 'alwaysApply: true' '---' ''
    printf '%s\n\n' '# Generated by dotagents'
    cat "$REPO_ROOT/AGENTS.md"
  } > "$target"
  echo "generated $target from $REPO_ROOT/AGENTS.md"

  INSTALL_SHARED_SKILLS=true
}

install_zed() {
  # Zed reads this global file in every agent session
  link_file "$REPO_ROOT/AGENTS.md" "$ZED_HOME/AGENTS.md"
  INSTALL_SHARED_SKILLS=true
}

install_claude() {
  # Claude Code uses CLAUDE.md for personal standing instructions
  link_file "$REPO_ROOT/AGENTS.md" "$CLAUDE_HOME/CLAUDE.md"
  python3 "$REPO_ROOT/scripts/merge-settings.py" \
    "$REPO_ROOT/settings/claude.json" "$CLAUDE_HOME/settings.json"
  INSTALL_CLAUDE_SKILLS=true
}

install_copilot() {
  # Copilot CLI and the VS Code agent read user instructions and settings here
  link_file "$REPO_ROOT/AGENTS.md" "$COPILOT_HOME/copilot-instructions.md"
  python3 "$REPO_ROOT/scripts/merge-settings.py" \
    "$REPO_ROOT/settings/copilot.json" "$COPILOT_HOME/settings.json"
  INSTALL_SHARED_SKILLS=true
}

# Install only the explicitly selected agent integrations
for target in "$@"; do
  case "$target" in
    cursor) install_cursor ;;
    zed) install_zed ;;
    claude) install_claude ;;
    copilot) install_copilot ;;
  esac
done

# Cursor, Zed, and Copilot share the open Agent Skills location
if [[ "$INSTALL_SHARED_SKILLS" == true ]]; then
  link_skills "$AGENTS_HOME/skills"
fi
if [[ "$INSTALL_CLAUDE_SKILLS" == true ]]; then
  link_skills "$CLAUDE_HOME/skills"
fi

echo "done"
